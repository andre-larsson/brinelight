#!/usr/bin/env node
/* The game's music, as files the page loads as plain scripts (so index.html still works from disk):
     node tools/music.js                    js/music-score.js from music/brinelight.scrim (run it after editing the score)
     node tools/music.js --vendor [DIR]     also bundle musicbox's src/ from a clone (default ../musicbox) into
                                            js/vendor/musicbox/, with its LICENSE and NOTICE
   musicbox is ES modules; the bundle wraps each module in a function and links them by name, in one script that
   sets window.Musicbox. tests/music.test.js checks the score file matches the .scrim and compiles cleanly. */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');
const SCORE = path.join(root, 'music/brinelight.scrim');
const SCORE_JS = path.join(root, 'js/music-score.js');
const VENDOR = path.join(root, 'js/vendor/musicbox');
const MODULES = ['score', 'random', 'synth', 'player']; // in dependency order

function scoreJs(text) {
  return '/* Generated by tools/music.js from music/brinelight.scrim: edit the .scrim, then run node tools/music.js. */\n'
    + `(globalThis.BL = globalThis.BL || {}).MUSIC_SCORE = ${JSON.stringify(text)};\n`;
}

// one ES module as a function body: imports read earlier modules, exports become the returned object
function wrap(name, src) {
  const names = [];
  const list = (s) => s.split(',').map((x) => x.trim()).filter(Boolean);
  let body = src
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([a-z]+)\.js';/gm, (_, ids, from) => {
      if (!MODULES.includes(from)) throw new Error(`${name}.js imports ${from}.js, which the bundle leaves out`);
      return `const { ${list(ids).map((x) => x.replace(/\s+as\s+/, ': ')).join(', ')} } = M.${from};`;
    })
    .replace(/^export\s*\{([^}]*)\};?/gm, (_, ids) => { names.push(...list(ids)); return ''; })
    .replace(/^export\s+((?:async\s+)?function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, id) => { names.push(id); return `${kw} ${id}`; });
  if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${name}.js has an import or export the bundle can't read`);
  if (/\bimport\.meta\b|\bimport\(/.test(body)) throw new Error(`${name}.js uses import.meta or import()`);
  return `M.${name} = (function () {\n'use strict';\n${body.trim()}\nreturn { ${names.join(', ')} };\n})();\n`;
}

function vendor(dir) {
  const src = path.join(dir, 'src');
  let commit = 'unknown', dirty = false;
  try {
    commit = execFileSync('git', ['-C', dir, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
    dirty = execFileSync('git', ['-C', dir, 'status', '--porcelain', 'src', 'LICENSE', 'NOTICE'], { encoding: 'utf8' }).trim() !== '';
  } catch (e) { /* not a git clone */ }
  const parts = MODULES.map((m) => wrap(m, fs.readFileSync(path.join(src, m + '.js'), 'utf8')));
  const out = `/* musicbox ${commit}${dirty ? ' (with uncommitted changes)' : ''}: https://github.com/andre-larsson/musicbox
   Apache License 2.0; see LICENSE and NOTICE beside this file. Bundled by tools/music.js from src/${MODULES.join('.js, src/')}.js,
   unchanged apart from the import and export lines. Sets window.Musicbox = { MusicPlayer, compile }. */
(function () {
const M = {};
${parts.join('\n')}
globalThis.Musicbox = { MusicPlayer: M.player.MusicPlayer, compile: M.score.compile, createSynth: M.synth.createSynth, version: ${JSON.stringify(commit)} };
})();
`;
  fs.mkdirSync(VENDOR, { recursive: true });
  fs.writeFileSync(path.join(VENDOR, 'musicbox.js'), out);
  for (const f of ['LICENSE', 'NOTICE']) fs.copyFileSync(path.join(dir, f), path.join(VENDOR, f));
  console.log(`js/vendor/musicbox/musicbox.js: musicbox ${commit}${dirty ? ' (dirty)' : ''}, ${(out.length / 1024).toFixed(0)} KB`);
}

if (require.main === module) {
  const vi = process.argv.indexOf('--vendor');
  if (vi >= 0) {
    const arg = process.argv[vi + 1];
    vendor(path.resolve(arg && !arg.startsWith('--') ? arg : path.join(root, '..', 'musicbox')));
  }
  fs.writeFileSync(SCORE_JS, scoreJs(fs.readFileSync(SCORE, 'utf8')));
  console.log('js/music-score.js: from music/brinelight.scrim');
}

module.exports = { scoreJs, SCORE, SCORE_JS, VENDOR };
